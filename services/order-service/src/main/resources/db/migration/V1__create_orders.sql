CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku            VARCHAR(32)  NOT NULL,
    quantity       INTEGER      NOT NULL,
    status         VARCHAR(16)  NOT NULL,
    failure_reason VARCHAR(512),
    created_at     TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_orders_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'REJECTED', 'FAILED'))
);

-- "Latest orders" listing sorts by created_at; dashboards and on-call queries filter by status.
CREATE INDEX idx_orders_created_at ON orders (created_at DESC);
CREATE INDEX idx_orders_status ON orders (status);
